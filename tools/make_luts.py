#!/usr/bin/env python3
"""Generate the camera log to Rec.709 (BT.1886) LUTs in luts/.

The LUTs are technical conversions built from the manufacturers' published
log curves and gamut primaries (via colour-science), followed by a simple
filmic tone curve. They are not the manufacturers' own LUTs.

Input: camera log RGB with video levels mapped to 0-1 (as in DaVinci Resolve).
Output: Rec.709 primaries, BT.1886 (gamma 2.4) display encoding, 0-1.

Usage: pip install colour-science numpy; python3 tools/make_luts.py [outdir]
"""

import os
import sys
import warnings

import numpy as np

warnings.filterwarnings("ignore")
import colour  # noqa: E402

SIZE = 33

# Display-linear value of 18% scene grey, and the scene value that reaches
# display white (about 6.5 stops above grey; lower for curves that end
# earlier, such as S-Log2, so that their brightest value is still white).
GREY_OUT = 0.11
WHITE_IN = 16.0
CONTRAST = 1.2
# Shadow toe: darkens the deepest shadows like a camera Rec.709 curve.
TOE = 0.01


def legal_to_full(x):
    return (x * 876 + 64) / 1023


def toe(f):
    return f * f * (1 + TOE) / (f + TOE)


def tonescale_params(white_in):
    # f(x) = m * (x / (x + s)) ** g, then toe(); toe(f(0.18)) = GREY_OUT and
    # f(white_in) = 1 (toe(1) = 1).
    g = CONTRAST
    grey = (GREY_OUT + (GREY_OUT ** 2 + 4 * (1 + TOE) * GREY_OUT * TOE) ** 0.5) / (2 * (1 + TOE))
    r = (1 / grey) ** (1 / g)
    lo, hi = 1e-6, 1e3
    for _ in range(200):
        s = (lo + hi) / 2
        ratio = (white_in / (white_in + s)) / (0.18 / (0.18 + s))
        if ratio > r:
            hi = s
        else:
            lo = s
    m = 1 / (white_in / (white_in + s)) ** g
    return m, s, g


def tonescale(x, params):
    m, s, g = params
    x = np.maximum(x, 0)
    return np.clip(toe(m * (x / (x + s)) ** g), 0, 1)


def decoder(name, legal=True, **kwargs):
    def decode(x):
        y = legal_to_full(x) if legal else x
        return colour.cctf_decoding(y, function=name, **kwargs)
    return decode


# (folder, file name, title, log decoding, camera gamut)
LUTS = [
    ("Sony", "S-Log3 S-Gamut3.Cine to Rec709", "S-Log3 S-Gamut3.Cine",
     decoder("S-Log3"), "S-Gamut3.Cine"),
    ("Sony", "S-Log3 S-Gamut3 to Rec709", "S-Log3 S-Gamut3",
     decoder("S-Log3"), "S-Gamut3"),
    ("Sony", "S-Log3 Venice S-Gamut3.Cine to Rec709", "S-Log3 Venice S-Gamut3.Cine",
     decoder("S-Log3"), "Venice S-Gamut3.Cine"),
    ("Sony", "S-Log3 Venice S-Gamut3 to Rec709", "S-Log3 Venice S-Gamut3",
     decoder("S-Log3"), "Venice S-Gamut3"),
    ("Sony", "S-Log2 S-Gamut to Rec709", "S-Log2 S-Gamut",
     decoder("S-Log2"), "S-Gamut"),
    ("ARRI", "LogC3 AWG3 EI800 to Rec709", "ARRI LogC3 (EI 800) AWG3",
     decoder("ARRI LogC3"), "ARRI Wide Gamut 3"),
    ("ARRI", "LogC4 AWG4 to Rec709", "ARRI LogC4 AWG4",
     decoder("ARRI LogC4"), "ARRI Wide Gamut 4"),
    ("Blackmagic", "Film Gen5 to Rec709", "Blackmagic Film Gen 5",
     decoder("Blackmagic Film Generation 5", legal=False), "Blackmagic Wide Gamut"),
    ("Blackmagic", "DaVinci Intermediate DWG to Rec709", "DaVinci Intermediate DWG",
     decoder("DaVinci Intermediate", legal=False), "DaVinci Wide Gamut"),
]


def make_lut(decode, gamut):
    axis = np.linspace(0, 1, SIZE)
    # .cube order: red changes fastest.
    b, g, r = np.meshgrid(axis, axis, axis, indexing="ij")
    rgb = np.stack([r, g, b], axis=-1).reshape(-1, 3)
    lin = decode(rgb)
    lin = colour.RGB_to_RGB(lin, colour.RGB_COLOURSPACES[gamut],
                            colour.RGB_COLOURSPACES["ITU-R BT.709"])
    params = tonescale_params(min(WHITE_IN, float(decode(np.array(1.0)))))
    return tonescale(lin, params) ** (1 / 2.4)


def write_cube(path, title, data):
    with open(path, "w", newline="\n") as f:
        f.write(f'TITLE "{title} to Rec.709 BT.1886 (mpv_tc)"\n')
        f.write("# Generated by tools/make_luts.py. Input: video levels mapped to 0-1.\n")
        f.write(f"LUT_3D_SIZE {SIZE}\n")
        for v in data:
            f.write(f"{v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "luts")
    for folder, name, title, decode, gamut in LUTS:
        os.makedirs(os.path.join(out, folder), exist_ok=True)
        path = os.path.join(out, folder, name + ".cube")
        write_cube(path, title, make_lut(decode, gamut))
        print(path)


if __name__ == "__main__":
    main()
